/** 取篇目中考等级 */
export function examLevel(title: string): 'must' | 'core' | 'normal' {
  return EXAM_TAGS[title]?.level ?? 'normal';
}

/** 取篇目中考等级 (alias, 返回 null 若未标记) */
export function examTagFor(title: string): 'must' | 'core' | null {
  return EXAM_TAGS[title] ? (EXAM_TAGS[title].level === 'normal' ? null : EXAM_TAGS[title].level) : null;
}

/** 取篇目核心考点 */
export function examPoints(title: string): string[] {
  return EXAM_TAGS[title]?.points ?? [];
}

/** 中考必考篇目排序权重 (must=0, core=1, normal=2) */
export function examOrder(title: string): number {
  return { must: 0, core: 1, normal: 2 }[examLevel(title)] ?? 2;
}
